# Restores i18n keys that were wrongly pruned because they're referenced
# dynamically (via NAV_ITEMS labels, column headers, etc.) not as string
# literals in translate pipes.
import json, io, os, re

all_keys = set()
for root, dirs, files in os.walk('src'):
    for f in files:
        if not f.endswith(('.ts', '.html')):
            continue
        text = io.open(os.path.join(root, f), encoding='utf-8').read()
        for m in re.finditer(r"'([a-z]{2,}(?:\.[a-z0-9_]+){2,})'", text):
            all_keys.add(m.group(1))

current = json.load(io.open('src/assets/i18n/ar.json', encoding='utf-8'))

def flat(obj, prefix=''):
    keys = set()
    for k, v in obj.items():
        full = f'{prefix}.{k}' if prefix else k
        if isinstance(v, dict):
            keys.update(flat(v, full))
        else:
            keys.add(full)
    return keys

existing = flat(current)
missing = all_keys - existing
print(f'referenced={len(all_keys)} existing={len(existing)} missing={len(missing)}')

