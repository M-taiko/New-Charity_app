def ts_literal(v):
    if v is None:
        return 'null'
    if v is True:
        return 'true'
    if v is False:
        return 'false'
    if isinstance(v, str):
        return repr(v).replace("'", '"') if v and v[0].isalpha() and not v[0].isdigit() else f"'{v}'"
    return str(v)


def form_page(spec):
    fields = spec['fields']
    modules = set(['TranslatePipe', 'RouterLink', 'FormsModule', 'ButtonModule', 'PageHeaderComponent'])
    body = []
    for field in fields:
        name, label, kind = field[0], field[1], field[2]
        required = 'required' if len(field) > 3 and field[3] else ''
        mod, control = FIELD_TYPES[kind]
        modules.add(mod)
        control = control.format(f=name, req=required, opts=field[4] if kind == 'select' else '[]')
        req_star = ' <span class="field__required" aria-hidden="true">*</span>' if required else ''
        body.append(f'''        <div class="field">
          <label class="field__label" for="{spec['selector']}-{name}">{{{{ '{label}' | translate }}}}{req_star}</label>
          {control}
        </div>''')
    fields_body = '\n'.join(body)
    model_init = '\n'.join(f"  {name}: {init};" for name, init in spec['model'].items())

    model_interface = f"interface {spec['model_name']} {{ [key: string]: string | number | boolean | null | undefined | string[] }}"
    return f"""// Generated by scripts/gen-pages3.py — hand-refine freely.
{FORM_IMPORTS}

{model_interface}

{spec['doc']}
@Component({{
  selector: '{spec['selector']}',
  standalone: true,
  imports: [{', '.join(sorted(modules))}],
  changeDetection: ChangeDetectionStrategy.OnPush,
  template: `
    <app-page-header [title]="isEdit() ? ('{spec['edit_title']}' | translate) : ('{spec['title']}' | translate)" />
    <form class="form-section" (ngSubmit)="save()" #f="ngForm">
      <div class="form-section__grid">
{fields_body}
      </div>
      @if (error()) {{ <div class="dialog__alert" role="alert">{{{{ error() }}}}</div> }}
      <div class="sticky-actions">
        <p-button [label]="'common.back' | translate" severity="secondary" [text]="true" routerLink="{spec['back']}" />
        <p-button type="submit" [label]="'{spec['submit']}' | translate" [loading]="sending()" [disabled]="f.invalid || sending()" />
      </div>
    </form>
  `,
}})
export class {spec['class']} {{
  private http = inject(HttpClient);
  private router = inject(Router);
  private toast = inject(ToastService);

  id = input<number | undefined>(undefined);
  isEdit = computed(() => this.id() !== undefined);
  sending = signal(false);
  error = signal('');

  model: {spec['model_name']} = {{
{chr(10).join('    ' + name + ': ' + ts_literal(default) + ',' for name, default in spec['defaults'].items())}
  }};

  options = {spec['options']};

  fid(name: string): string {{ return this.selectorId() + '-' + name; }}
  private counter = 0;
  selectorId(): string {{ return '{spec['selector']}'; }}
  set(key: string, value: unknown): void {{ (this.model as Record<string, unknown>)[key] = value; }}

  ngOnInit(): void {{
    const id = this.id();
    if (id !== undefined) {{
      firstValueFrom(this.http.get<ItemResponse<{spec['model_name']}>>('{spec['endpoint']}/' + id)).then((res) => {{
        this.model = {{ ...this.model, ...res.data }};
      }});
    }}
  }}

  save(): void {{
    this.sending.set(true);
    this.error.set('');
    const id = this.id();
    const request$ = id
      ? this.http.post<ActionResponse>('{spec['endpoint']}/' + id + '{spec['update_action']}', this.model)
      : this.http.post<ActionResponse>('{spec['endpoint']}', this.model);
    firstValueFrom(request$).then((res) => {{
      this.sending.set(false);
      this.toast.success(res.message);
      void this.router.navigateByUrl('{spec['back']}');
    }}).catch((err: HttpErrorResponse) => {{
      this.sending.set(false);
      this.error.set(err.error?.message ?? 'errors.generic');
    }});
  }}
}}
"""


